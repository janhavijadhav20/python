print("================= STAR PATTERN =================\n")

n = 5

for i in range(n):
    for j in range(n):
        print("*", end=" ")
    print()

print("----------------------------------------------------------------\n")

n = 5

for i in range(1, n + 1):
    print("* " * i)

print("----------------------------------------------------------------\n")

n = 5

for i in range(n, 0, -1):
    print("* " * i)

print("----------------------------------------------------------------\n")

n = 5

for i in range(n):
    print(" " * (n - i - 1) + "* " * (i + 1))

print("----------------------------------------------------------------\n")

n = 5

for i in range(n, 0, -1):
    print(" " * (n - i) + "* " * i)

print("----------------------------------------------------------------\n")

n = 5

for i in range(n):
    print(" " * (n - i - 1) + "* " * (i + 1))

for i in range(n - 2, -1, -1):
    print(" " * (n - i - 1) + "* " * (i + 1))

print("----------------------------------------------------------------\n")

n = 5

for i in range(n):
    for j in range(n):
        if i == 0 or i == n - 1 or j == 0 or j == n - 1:
            print("*", end=" ")
        else:
            print(" ", end=" ")
    print()

print("----------------------------------------------------------------\n")

n = 5

for i in range(1, n + 1):
    for j in range(1, i + 1):
        print(j, end=" ")
    print()

print("----------------------------------------------------------------\n")

n = 5

for i in range(1, n + 1):
    print((str(i) + " ") * i)

